def _read_doc(name: str) -> str:
    return (_DOCS_DIR / f"{name}.txt").read_text(encoding="utf-8")


def _extract(text: str, start: str, stop: Optional[str] = None) -> str:
    i = text.find(start)
    if i == -1:
        return ""
    if stop:
        j = text.find(stop, i + len(start))
        if j == -1:
            return text[i:].strip()
        return text[i:j].strip()
    return text[i:].strip()


def _multi_extract(text: str, ranges: List[Tuple[str, Optional[str]]]) -> str:
    parts = [_extract(text, s, e) for s, e in ranges]
    return "\n\n".join(p for p in parts if p)


